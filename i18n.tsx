function interpolate(text: string, values?: Record<string, string | number>) {
  return text.replace(/\{(\w+)\}/g, (_, key) => String(values?.[key] ?? `{${key}}`));
}

export type Translator = (key: string, values?: Record<string, string | number>) => string;
const I18nContext = createContext<{ locale: Locale; t: Translator }>({
  locale: "en",
  t: (key) => key,
});

export function I18nProvider({ locale, children }: { locale: Locale; children: React.ReactNode }) {
  const dictionary = locale === "ja" ? ja : locale === "en" ? en : {};
  const t: Translator = (key, values) => interpolate(dictionary[key] ?? key, values);
  return <I18nContext.Provider value={{ locale, t }}>{children}</I18nContext.Provider>;
}

export function useI18n() { return useContext(I18nContext); }
