export type Locale = "zh" | "ja" | "en";

const preferenceKey = "cardledger.locale";

export function preferredLocale(): Locale {
  try {
    const saved = localStorage.getItem(preferenceKey);
    if (saved === "zh" || saved === "ja" || saved === "en") return saved;
    const language = navigator.languages?.[0] ?? navigator.language ?? "";
    if (language.toLowerCase().startsWith("zh")) return "zh";
    if (language.toLowerCase().startsWith("ja")) return "ja";
  } catch {
    // Private browsing or an unavailable browser preference falls back to English.
  }
  return "en";
}

export function rememberLocale(locale: Locale) {
  try { localStorage.setItem(preferenceKey, locale); } catch { /* Optional preference. */ }
}

